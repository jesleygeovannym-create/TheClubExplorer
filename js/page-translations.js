  function translateText(value) {
    if (i18n.getLang() !== "en") return String(value || "");
    return translationFor(value) || String(value || "");
  }

  var textSources = new WeakMap();
  var lastAppliedText = new WeakMap();
  var attributeSources = new WeakMap();
  // Los elementos marcados con data-i18n los controla directamente i18n.js.
  var skipText = "script,style,noscript,textarea,[contenteditable='true'],[data-i18n]";

  function normalize(value) {
    return String(value || "").trim().replace(/\s+/g, " ");
  }

  function translationFor(source) {
    var value = normalize(source);
    if (en[value]) return en[value];
    var match = value.match(/^(\d+) hoteles encontrados$/i);
    if (match) return match[1] + " hotels found";
    match = value.match(/^1 hotel encontrado$/i);
    if (match) return "1 hotel found";
    match = value.match(/^(\d+) opciones$/i);
    if (match) return match[1] + " options";
    match = value.match(/^Carrito (\d+) va a por ti$/i);
    if (match) return "Cart " + match[1] + " is on the way to pick you up";
    match = value.match(/^Carrito (\d+) ya llegó$/i);
    if (match) return "Cart " + match[1] + " has arrived";
    match = value.match(/^Carrito (\d+)$/i);
    if (match) return "Cart " + match[1];
    match = value.match(/^(\d+) m · (Disponible|En camino|En ruta|Llegando|En destino)$/i);
    if (match) {
      var cartState = { "Disponible": "Available", "En camino": "On the way", "En ruta": "On route", "Llegando": "Arriving", "En destino": "At destination" };
      return match[1] + " m · " + cartState[match[2]];
    }
    match = value.match(/^Llega en (\d+) min · ruta por calles$/i);
    if (match) return "Arrives in " + match[1] + " min · route through resort roads";
    match = value.match(/^Ruta (a pie|en coche) marcada dentro del mapa(?:: (.+))?\.$/i);
    if (match) return "Route " + (match[1] === "a pie" ? "on foot" : "by car") + " shown on the map" + (match[2] ? ": " + match[2] : ".");
    match = value.match(/^Carrito en tu ubicación · (.+)$/i);
    if (match) return "Cart at your location · " + match[1];
    match = value.match(/^Ir al paso (\d+)$/i);
    if (match) return "Go to step " + match[1];
    match = value.match(/^(\d+) de (\d+) lugares$/i);
    if (match) return match[1] + " of " + match[2] + " places";
    match = value.match(/^(\d+) lugares$/i);
    if (match) return match[1] + " places";
    match = value.match(/^¡Bienvenido! Nos alegra tenerte tan cerca de (.+)\. Preparamos todo para que tu visita sea mágica\.$/i);
    if (match) return "Welcome! We’re glad to have you near " + match[1] + ". We’ve prepared everything to make your visit special.";
    match = value.match(/^Solicitud ([\w-]+)(?: · (.+?))?(?: · ruta por calles)?$/i);
    if (match) return "Request " + match[1] + (match[2] ? " · " + match[2] : "") + (value.endsWith("ruta por calles") ? " · route through resort roads" : "");
    match = value.match(/^a unos (\d+) m de ti · (.+)$/i);
    if (match) return "about " + match[1] + " m from you · " + match[2];
    match = value.match(/^([\wÀ-ÿ .'-]+) · a unos (\d+) m de ti · (.+)$/i);
    if (match) return match[1] + " · about " + match[2] + " m from you · " + match[3];
    match = value.match(/^Ubicación detectada · (.+)$/i);
    if (match) return "Location detected · " + match[1];
    match = value.match(/^Te llevamos a (.+)$/i);
    if (match) return "We’ll take you to " + match[1];
    match = value.match(/^Recogida en (.+)$/i);
    if (match) return "Pickup at " + match[1];
    return "";
  }

  function translateNode(node) {
    if (!textSources.has(node) || (lastAppliedText.has(node) && node.nodeValue !== lastAppliedText.get(node))) {
      textSources.set(node, node.nodeValue);
    }
    var source = textSources.get(node);
    if (i18n.getLang() !== "en") {
      if (node.nodeValue !== source) node.nodeValue = source;
      lastAppliedText.set(node, source);
      return;
    }
    var translation = translationFor(source);
    if (!translation) {
      lastAppliedText.set(node, source);
      return;
    }
    var leading = (source.match(/^\s*/) || [""])[0];
    var trailing = (source.match(/\s*$/) || [""])[0];
    var result = leading + translation + trailing;
    if (node.nodeValue !== result) node.nodeValue = result;
    lastAppliedText.set(node, result);
  }

  function translateTree(root) {
    if (!root) return;
    var element = root.nodeType === Node.ELEMENT_NODE ? root : root.parentElement;
    if (!element || element.matches(skipText)) return;
    var walker = document.createTreeWalker(element, NodeFilter.SHOW_TEXT);
    while (walker.nextNode()) {
      var node = walker.currentNode;
      if (node.parentElement && node.parentElement.closest(skipText)) continue;
      translateNode(node);
    }

    var elements = [element].concat(Array.from(element.querySelectorAll("*")));
    elements.forEach(function (item) {
      if (item.matches("[data-i18n], [data-i18n-aria], [data-i18n-placeholder]")) return;
      ["placeholder", "aria-label", "title", "alt"].forEach(function (attribute) {
        if (!item.hasAttribute(attribute)) return;
        var originals = attributeSources.get(item);
        if (!originals) {
          originals = {};
          attributeSources.set(item, originals);
        }
        if (!(attribute in originals)) originals[attribute] = item.getAttribute(attribute);
        var source = originals[attribute];
        var next = i18n.getLang() === "en" ? (translationFor(source) || item.getAttribute(attribute)) : source;
        if (item.getAttribute(attribute) !== next) item.setAttribute(attribute, next);
      });
    });
  }

  function translateDocument() {
    if (document.body) translateTree(document.body);
  }

  window.addEventListener("languagechange", translateDocument);
  window.RevistaDigital.pageTranslations = { translateText: translateText };
  if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", translateDocument, { once: true });
  } else {
    translateDocument();
  }

  if (document.body && window.MutationObserver) {
    var observer = new MutationObserver(function (records) {
      records.forEach(function (record) {
        if (record.type === "characterData") translateNode(record.target);
        else record.addedNodes.forEach(translateTree);
      });
    });
    observer.observe(document.body, { subtree: true, childList: true, characterData: true });
  }
